import { mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { env } from '../../config/env';
import { logger } from '../logger';

/**
 * File storage port. Module 1 stores files on local disk; an S3/GCS adapter can implement the
 * same interface later without touching callers.
 */
export interface FileStorage {
  /** Persist bytes under a server-generated key and return the public URL to store on the record. */
  save(input: { key: string; body: Buffer; contentType: string }): Promise<{ url: string }>;
  /** Best-effort removal by public URL. Unknown or foreign URLs are ignored. */
  remove(url: string): Promise<void>;
}

export const PUBLIC_UPLOAD_PREFIX = '/uploads';

/** Keys are generated by the server only; this guards against path traversal anyway. */
const SAFE_KEY = /^[A-Za-z0-9][A-Za-z0-9/_.-]*$/;

export class LocalDiskStorage implements FileStorage {
  readonly rootDir: string;

  constructor(rootDir: string, private readonly publicPrefix = PUBLIC_UPLOAD_PREFIX) {
    this.rootDir = path.resolve(rootDir);
  }

  private resolveKey(key: string): string {
    if (!SAFE_KEY.test(key) || key.includes('..')) throw new Error(`Unsafe storage key: ${key}`);
    const full = path.resolve(this.rootDir, key);
    if (!full.startsWith(this.rootDir + path.sep)) throw new Error(`Storage key escapes root: ${key}`);
    return full;
  }

  async save({ key, body }: { key: string; body: Buffer; contentType: string }) {
    const full = this.resolveKey(key);
    await mkdir(path.dirname(full), { recursive: true });
    await writeFile(full, body, { flag: 'wx' });
    return { url: `${this.publicPrefix}/${key}` };
  }

  async remove(url: string) {
    if (!url.startsWith(`${this.publicPrefix}/`)) return;
    try {
      await rm(this.resolveKey(url.slice(this.publicPrefix.length + 1)), { force: true });
    } catch (err) {
      logger.warn({ err, url }, 'Could not remove stored file');
    }
  }
}

export const storage = new LocalDiskStorage(env.UPLOAD_DIR);

// ───────────────────────────────────────────────────────────── image sniffing

export const IMAGE_TYPES = {
  png: 'image/png',
  jpg: 'image/jpeg',
  webp: 'image/webp',
} as const;

/**
 * Detect the image type from its magic bytes. The client-sent MIME type and file name are never
 * trusted. SVG is deliberately unsupported (it can carry scripts).
 */
export function sniffImageType(buf: Buffer): keyof typeof IMAGE_TYPES | null {
  if (buf.length >= 8 && buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return 'png';
  if (buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return 'jpg';
  if (buf.length >= 12 && buf.toString('ascii', 0, 4) === 'RIFF' && buf.toString('ascii', 8, 12) === 'WEBP') return 'webp';
  return null;
}
